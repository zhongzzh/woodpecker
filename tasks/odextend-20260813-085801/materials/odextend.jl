@testset "ode15i" begin
    function _weissinger(t, y, yp)
        return @. t * y^2 * yp^3 - y^3 * yp^2 + t * (t^2 + 1) * yp - t^2 * y
    end
    t0 = 1
    y0 = sqrt(3 / 2)
    yp0 = 0
    y0, yp0 = decic(_weissinger, t0, y0, 1, yp0, 0)
    sol = ode15i(_weissinger, [1 10], y0, yp0; output_sol=ReturnStruct)
    sol_new = odextend(sol, _weissinger, 20)
    @test isapprox(x10, sol_new.x, atol=1e-10, rtol=1e-10)
    @test isapprox(y10, sol_new.y, atol=1e-7, rtol=1e-7)
    sol_new = odextend(sol, _weissinger, 20, [sol.y[:, end] sol.idata.ypfinal])
    @test isapprox(x10, sol_new.x, atol=1e-10, rtol=1e-10)
    @test isapprox(y10, sol_new.y, atol=1e-7, rtol=1e-7)
end

@testset "error" begin
    function ddex1de(t, y, Z)
        ylag1 = Z[:, 1]
        ylag2 = Z[:, 2]

        return [
            ylag1[1]
            ylag1[1] + ylag2[2]
            y[2]
        ]
    end
    function history(t)
        return ones(3, 1)
    end
    sol = dde23(ddex1de, [1 0.2], history, [0 5])
    msg = "solver 中出现错误的求解器名称 dde23。"
    @test_throws ArgumentError(msg) odextend(sol, ddex1de, 0)

    tspan = [0 20]
    y0 = [2 0]
    vdp1 = (t, y) -> [y[2]; (1 - y[1]^2) * y[2] - y[1]]
    sol = ode45(vdp1, tspan, y0; output_sol=ReturnStruct)
    msg = "在 [0.0, 20.0] 中得到的解不能扩展至 -1。"
    @test_throws ArgumentError(msg) odextend(sol, vdp1, -1)

    tspan = [20 0]
    y0 = [2 0]
    vdp1 = (t, y) -> [y[2]; (1 - y[1]^2) * y[2] - y[1]]
    sol = ode45(vdp1, tspan, y0; output_sol=ReturnStruct)
    msg = "在 [20.0, 0.0] 中得到的解不能扩展至 25。"
